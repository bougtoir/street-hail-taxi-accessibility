#!/usr/bin/env python3
"""Reviewer quick check: verify MANIFEST.csv, then regenerate the canonical
numerical registry from the archived tables and confirm byte identity."""
import csv, hashlib, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = "analysis/canonical_results.json"


def sha(p):
    return hashlib.sha256(open(os.path.join(ROOT, p), "rb").read()).hexdigest()


rows = list(csv.DictReader(open(os.path.join(ROOT, "MANIFEST.csv"))))
bad = [r["path"] for r in rows if sha(r["path"]) != r["sha256"]]
if bad:
    sys.exit(f"FAIL manifest mismatch: {bad}")
print(f"PASS manifest: {len(rows)} files match SHA-256")

expected = next(r["sha256"] for r in rows if r["path"] == REG)
subprocess.run([sys.executable, os.path.join(ROOT, "analysis/build_canonical_results.py")], check=True)
got = sha(REG)
if got != expected:
    sys.exit(f"FAIL registry regenerated with SHA-256 {got}, expected {expected}")
print(f"PASS canonical registry regenerated byte-identical: {got}")
