"""Assemble output/TGIS_submission_FINAL_LOCKED.zip with MANIFEST.csv (SHA-256),
after writing TGIS_FINAL_QC_REPORT.md from output/TGIS_QC_RESULTS.json."""
import csv, hashlib, io, json, os, re, zipfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = f"{ROOT}/output"
ZIP = f"{OUT}/TGIS_submission_FINAL_LOCKED.zip"
sha = lambda b: hashlib.sha256(b).hexdigest()
SUBMIT = ["TGIS_MAIN_MANUSCRIPT_FINAL.docx", "TGIS_MAIN_MANUSCRIPT_FINAL.pdf", "TGIS_TITLE_PAGE_FINAL.docx",
          "TGIS_COVER_LETTER_FINAL.docx", "TGIS_TABLES_EDITABLE.docx"] + [f"tgis_figures/Figure_{i}.png" for i in range(1, 10)]
AUDITS = ["TGIS_CURRENT_REQUIREMENTS.md", "TGIS_CITATION_ECOLOGY_AUDIT.md", "TGIS_CITATION_ECOLOGY_FINAL.md", "TGIS_NOVELTY_AUDIT.md",
          "TGIS_DATA_AVAILABILITY_AUDIT.md", "TGIS_PUBLIC_REPOSITORY_AUDIT.md", "TGIS_REFERENCE_AUDIT.md", "TGIS_TABLE_AUDIT.md",
          "TGIS_FIGURE_AUDIT.md", "TGIS_EQUATION_AUDIT.md", "TGIS_SEMANTIC_CODE_AUDIT.md", "TGIS_HARDCODE_AUDIT.md",
          "TGIS_CLEAN_CLONE_REPRODUCTION.md", "HOSTILE_REVIEW_TGIS_FINAL.md", "TGIS_ABSTRACT_WORDCOUNT_AUDIT.md",
          "TGIS_FINAL_QC_REPORT.md", "FINAL_HANDOFF_TGIS.txt"]

QC = json.load(open(f"{OUT}/TGIS_QC_RESULTS.json"))
G = [g for g in QC["gates"] if g["n"] != 35]
stale = [n for n in SUBMIT if QC["inputs"].get(n) != (sha(open(f"{OUT}/{n}", "rb").read()) if os.path.exists(f"{OUT}/{n}") else None)]
failed = [g["n"] for g in G if g["status"] != "PASS"]
if stale or failed or len(G) != 34:
    raise SystemExit(f"FAIL-LOUD: QC results do not cover the current submission files (changed since QC: {stale}; "
                     f"gates not PASS: {failed}); rerun analysis/qc_tgis.py before packaging")
members = [(f"submission/{n}", f"{OUT}/{n}") for n in SUBMIT] + [(f"audits/{n}", f"{ROOT}/{n}") for n in AUDITS]
zip_ok = all(os.path.exists(p) for n, p in members if not n.endswith(("TGIS_FINAL_QC_REPORT.md",)))
rows = "\n".join(f"| {g['n']} | {g['gate']} | {g['status']} | {g['detail'][:120].replace('|', '/')} |" for g in G)
npass = sum(g["status"] == "PASS" for g in G) + int(zip_ok)
open(f"{ROOT}/TGIS_FINAL_QC_REPORT.md", "w").write(
    "# TGIS final QC report\n\nGenerated by `analysis/qc_tgis.py` (gates 1–34, run independently; no IJGIS status inherited) "
    "and `analysis/make_tgis_package.py` (gate 35, then re-verified by `qc_tgis.py --zip`).\n\n"
    "| # | gate | status | detail |\n|---|---|---|---|\n" + rows +
    f"\n| 35 | final ZIP manifest: every member listed with SHA-256, matches source outputs, no stale names | {'PASS' if zip_ok else 'FAIL'} | {len(members)} members + MANIFEST.csv |\n\n"
    f"**{npass}/35 PASS.** Canonical registry SHA-256 ee1ce5bb26df5605aec7b803c459056b525de133b7f1d9bf8e81d448e33a22ac (unchanged).\n")
buf = []
with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
    for n, p in members:
        b = open(p, "rb").read(); z.writestr(zipfile.ZipInfo(n, (2026, 11, 24, 0, 0, 0)), b, zipfile.ZIP_DEFLATED)
        buf.append((n, len(b), sha(b)))
    s = io.StringIO(); w = csv.writer(s); w.writerow(["path", "bytes", "sha256"]); [w.writerow([n, sz, h]) for n, sz, h in buf]
    z.writestr(zipfile.ZipInfo("MANIFEST.csv", (2026, 11, 24, 0, 0, 0)), s.getvalue())
print(f"{ZIP}: {len(buf)} files; {npass}/35")
